export type SpriteKind =
  | "fox"
  | "chief"
  | "jonesy"
  | "peely"
  | "kit"
  | "badkit"
  | "sonic"
  | "phantom"
  | "viper"
  | "stormstep";

export type EmoteId = "wave" | "floss" | "griddy" | "take-l" | "hiss";
export type SidekickId = "none" | "cat" | "dog" | "llama";

export function spriteRows(kind: SpriteKind, frame: number) {
  if (kind === "chief") return frame ? CHIEF_B : CHIEF_A;
  if (kind === "jonesy") return frame ? JONESY_B : JONESY_A;
  if (kind === "peely") return frame ? PEELY_B : PEELY_A;
  if (kind === "kit") return frame ? KIT_B : KIT_A;
  if (kind === "badkit") return frame ? BADKIT_B : BADKIT_A;
  if (kind === "sonic") return frame ? SONIC_B : SONIC_A;
  if (kind === "phantom") return frame ? PHANTOM_B : PHANTOM_A;
  if (kind === "viper") return frame ? VIPER_B : VIPER_A;
  if (kind === "stormstep") return frame ? SONIC_B : SONIC_A;
  return frame ? FOX_B : FOX_A;
}

export function idlePose(tick: number) {
  return {
    ox: 0,
    oy: Math.sin(tick / 18) * 1,
    flip: false,
    frame: 0 as 0 | 1,
  };
}

export function danceFrame(tick: number): 0 | 1 | 2 {
  return (Math.floor(tick / 6) % 3) as 0 | 1 | 2;
}

export function emotePose(id: EmoteId, tick: number) {
  const frame = danceFrame(tick);
  const t = tick / 4;
  if (id === "floss") {
    return {
      ox: Math.sin(t * 2.2) * 10,
      oy: frame === 1 ? 3 : frame === 2 ? 0 : -2,
      flip: frame === 2,
      frame: (frame % 2) as 0 | 1,
      dance: frame,
    };
  }
  if (id === "griddy") {
    return {
      ox: (frame - 1) * 8,
      oy: frame === 1 ? 4 : 0,
      flip: frame === 0,
      frame: (frame % 2) as 0 | 1,
      dance: frame,
    };
  }
  if (id === "take-l") {
    return {
      ox: 0,
      oy: frame === 1 ? -6 : 2,
      flip: false,
      frame: 1 as 0 | 1,
      dance: frame,
    };
  }
  if (id === "hiss") {
    return {
      ox: Math.sin(t * 10) * 3,
      oy: frame === 2 ? -3 : 0,
      flip: false,
      frame: (frame % 2) as 0 | 1,
      dance: frame,
    };
  }
  return {
    ox: Math.sin(t * 1.4) * 8,
    oy: frame === 1 ? -5 : 1,
    flip: frame === 2,
    frame: (frame % 2) as 0 | 1,
    dance: frame,
  };
}

export function drawDanceExtras(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  facing: number,
  frame: 0 | 1 | 2,
  accent: string
) {
  const dir = facing >= 0 ? 1 : -1;
  ctx.fillStyle = accent;
  if (frame === 0) {
    ctx.fillRect(x + 2, y + 6, 3, 2);
    ctx.fillRect(x + 11, y + 6, 3, 2);
    ctx.fillRect(x + (dir > 0 ? 14 : -1), y + 4, 3, 2);
  } else if (frame === 1) {
    ctx.fillRect(x + 1, y + 9, 4, 2);
    ctx.fillRect(x + 11, y + 9, 4, 2);
    ctx.fillRect(x + 6, y - 1, 4, 2);
  } else {
    ctx.fillRect(x + (dir > 0 ? 13 : -2), y + 12, 5, 2);
    ctx.fillRect(x + 3, y + 5, 2, 3);
    ctx.fillRect(x + 11, y + 5, 2, 3);
  }
}

