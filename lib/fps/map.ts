export function buildMapGrid() {
  const lines = RAW.split("\n").map((l) => l.trim());
  const grid: number[][] = [];
  for (let y = 0; y < MAP_H; y++) {
    const row: number[] = [];
    for (let x = 0; x < MAP_W; x++) {
      const ch = lines[y]?.[x] ?? "1";
      row.push(ch === "." ? 0 : Number(ch));
    }
    grid.push(row);
  }
  return grid;
}

